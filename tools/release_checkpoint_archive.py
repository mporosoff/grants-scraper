"""Preserve protected release artifacts as exact ZIPs in an independent run.

This is an authenticated transport, not replacement validation or spending
evidence. Original artifact payloads are never regenerated by this module.
"""
import argparse
import hashlib
import io
import json
import math
import os
from pathlib import Path, PurePosixPath
import re
import stat
import subprocess
import zipfile


SOURCE_WORKFLOW = '.github/workflows/refresh-opportunities.yml'
BACKUP_WORKFLOW = '.github/workflows/preserve-release-checkpoints.yml'
SCHEMA_VERSION = 1
MAX_PAGES = 100
MAX_ARTIFACTS = 200
MAX_ZIP_BYTES = 512 * 1024 * 1024
MAX_BUNDLE_BYTES = 1024 * 1024 * 1024
MAX_EXPANDED_BYTES = 2 * 1024 * 1024 * 1024
MAX_ZIP_MEMBERS = 20000
MAX_MANIFEST_BYTES = 4 * 1024 * 1024
BACKUP_NAME = re.compile(r'originalrun-([1-9][0-9]*)-attempt-([1-9][0-9]*)(?:-candidate-([a-f0-9]{64}))?'
                         r'(?:-task-([a-f0-9]{64})|-(tasks-mixed))?')
CANDIDATE_NAME = re.compile(r'(?:candidate|validation|publication|live)-([a-f0-9]{64})(?:-[1-9][0-9]*)?')
TASK_PREFIX = re.compile(r'offline-ai-[A-Za-z0-9][A-Za-z0-9_.-]*')
TASK_ARTIFACT = re.compile(r'(offline-ai-[A-Za-z0-9][A-Za-z0-9_.-]*)-(?:reservation|state)-[1-9][0-9]*-[1-9][0-9]*')
TERMINAL_CONCLUSIONS = frozenset({'success', 'failure', 'cancelled', 'skipped', 'timed_out',
                                  'action_required', 'neutral', 'stale', 'startup_failure'})
MANIFEST_KEYS = {'schema_version', 'artifact_name', 'source', 'source_conclusion', 'artifacts'}
ITEM_KEYS = {'metadata', 'path', 'zip_sha256', 'zip_bytes'}


def api(repository, path):
    return subprocess.check_output(['gh', 'api', f'repos/{repository}/{path}'], timeout=60)


def _json(value):
    return json.dumps(value, sort_keys=True, separators=(',', ':'), ensure_ascii=False, allow_nan=False).encode()


def _decode(raw):
    def pairs(items):
        value = {}
        for key, item in items:
            if key in value:
                raise ValueError('Duplicate checkpoint JSON key')
            value[key] = item
        return value
    def number(token):
        value = float(token)
        if not math.isfinite(value):
            raise ValueError('Nonfinite checkpoint JSON number')
        return value
    def constant(_):
        raise ValueError('Nonfinite checkpoint JSON constant')
    return json.loads(raw, object_pairs_hook=pairs, parse_float=number, parse_constant=constant)


def _sha(raw):
    return hashlib.sha256(raw).hexdigest()


def _positive(value):
    if isinstance(value, bool) or not re.fullmatch(r'[1-9][0-9]*', str(value)):
        raise ValueError('Invalid checkpoint identifier')
    return int(value)


def _repository(value):
    if not isinstance(value, str) or not re.fullmatch(r'[A-Za-z0-9_.-]+/[A-Za-z0-9_.-]+', value):
        raise ValueError('Invalid checkpoint repository')
    return value


def _pages(read, path, field, *, require_total=False):
    rows = []
    for page in range(1, MAX_PAGES + 1):
        value = _decode(read(f'{path}?per_page=100&page={page}'))
        chunk = value[field]
        if (not isinstance(chunk, list) or len(chunk) > 100
                or (require_total and (type(value.get('total_count')) is not int or value['total_count'] < 0))):
            raise ValueError('Invalid checkpoint artifact inventory')
        rows.extend(chunk)
        if len(chunk) < 100:
            if (value.get('total_count', len(rows)) > len(rows)
                    or (require_total and value['total_count'] != len(rows))):
                raise ValueError('Incomplete checkpoint artifact inventory')
            return rows
    raise ValueError('Checkpoint artifact inventory exceeds bounded lookup')


def _run_identity(repository, meta, run, attempt=None, *, backup=False):
    if (not isinstance(meta, dict) or _positive(meta.get('id')) != _positive(run)
            or meta.get('path') != (BACKUP_WORKFLOW if backup else SOURCE_WORKFLOW)
            or meta.get('head_branch') != 'main'
            or meta.get('event') not in ({'workflow_run'} if backup else {'push', 'schedule', 'workflow_dispatch'})
            or meta.get('status') != 'completed'
            or not isinstance(meta.get('conclusion'), str) or meta['conclusion'] not in TERMINAL_CONCLUSIONS
            or (backup and meta.get('conclusion') != 'success')
            or (meta.get('repository') or {}).get('full_name') != repository
            or (meta.get('head_repository') or {}).get('full_name') != repository
            or not re.fullmatch(r'[a-f0-9]{40}', str(meta.get('head_sha')))):
        raise ValueError('Untrusted protected checkpoint workflow origin')
    selected_attempt = _positive(meta.get('run_attempt'))
    if attempt is not None and selected_attempt != _positive(attempt):
        raise ValueError('Checkpoint workflow attempt changed')
    return {'repository': repository, 'repository_id': _positive(meta['repository']['id']),
            'head_repository_id': _positive(meta['head_repository']['id']),
            'run_id': str(run), 'run_attempt': selected_attempt,
            'workflow_id': _positive(meta.get('workflow_id')), 'head_sha': meta['head_sha'],
            'head_branch': meta['head_branch'], 'event': meta['event'], 'path': meta['path']}


def _artifact(metadata, source, *, outer=False):
    if not isinstance(metadata, dict):
        raise ValueError('Invalid preserved artifact metadata')
    identifier = _positive(metadata.get('id'))
    if (not re.fullmatch(r'[A-Za-z0-9][A-Za-z0-9_.-]{0,254}', str(metadata.get('name')))
            or metadata.get('expired') is not False
            or not isinstance(metadata.get('size_in_bytes'), int)
            or isinstance(metadata.get('size_in_bytes'), bool)
            or not 0 < metadata['size_in_bytes'] <= (MAX_BUNDLE_BYTES if outer else MAX_ZIP_BYTES)
            or not re.fullmatch(r'sha256:[a-f0-9]{64}', str(metadata.get('digest')))):
        raise ValueError('Invalid preserved artifact metadata or digest')
    workflow = metadata.get('workflow_run') or {}
    if (_positive(workflow.get('id')) != _positive(source['run_id'])
            or workflow.get('head_branch') != 'main' or workflow.get('head_sha') != source['head_sha']
            or _positive(workflow.get('repository_id')) != source['repository_id']
            or _positive(workflow.get('head_repository_id')) != source['head_repository_id']):
        raise ValueError('Artifact origin differs from its protected workflow')
    return identifier


def _candidate(inventory):
    identities = set()
    for item in inventory:
        if not isinstance(item, dict):
            raise ValueError('Invalid checkpoint inventory item')
        match = CANDIDATE_NAME.fullmatch(str(item.get('name')))
        if match:
            identities.add(match.group(1))
    if len(identities) > 1:
        raise ValueError('Multiple candidate identities cannot share a checkpoint archive')
    return next(iter(identities), None)


def artifact_name(run, attempt, inventory):
    name = f'originalrun-{_positive(run)}-attempt-{_positive(attempt)}'
    candidate = _candidate(inventory)
    name += '-candidate-' + candidate if candidate else ''
    prefixes, uncertain = set(), False
    for item in inventory:
        label = str(item.get('name'))
        if label.startswith('offline-ai-'):
            match = TASK_ARTIFACT.fullmatch(label)
            if match:
                prefixes.add(match.group(1))
            else:
                uncertain = True
    if uncertain or len(prefixes) > 1:
        return name + '-tasks-mixed'
    return name + ('-task-' + _sha(next(iter(prefixes)).encode()) if prefixes else '')


def _members(raw, *, outer=False):
    cap = MAX_BUNDLE_BYTES if outer else MAX_ZIP_BYTES
    if not isinstance(raw, bytes) or not 0 < len(raw) <= cap:
        raise ValueError('Checkpoint ZIP exceeds its byte limit')
    try:
        archive = zipfile.ZipFile(io.BytesIO(raw))
        infos = archive.infolist()
        if len(infos) > MAX_ZIP_MEMBERS or sum(info.file_size for info in infos) > MAX_EXPANDED_BYTES:
            raise ValueError('Checkpoint ZIP exceeds its expansion limit')
        names = set()
        for info in infos:
            path = PurePosixPath(info.filename)
            if (not info.filename or info.orig_filename != info.filename
                    or '\\' in info.filename or ':' in info.filename or path.is_absolute()
                    or any(part in {'.', '..', '.git'} for part in path.parts)
                    or info.filename.casefold() in names or info.flag_bits & 1
                    or stat.S_ISLNK(info.external_attr >> 16)):
                raise ValueError('Unsafe or duplicate checkpoint ZIP member')
            names.add(info.filename.casefold())
        return archive
    except (zipfile.BadZipFile, EOFError) as error:
        raise ValueError('Invalid checkpoint ZIP') from error


def _output_name(name):
    if os.environ.get('GITHUB_OUTPUT'):
        with Path(os.environ['GITHUB_OUTPUT']).open('a', encoding='utf-8') as handle:
            handle.write('artifact_name=' + name + '\n')


def capture(repository, run, attempt, output, *, api=None):
    """Save all currently retained ZIPs while the completed source is unchanged."""
    repository, run, attempt = _repository(repository), str(_positive(run)), _positive(attempt)
    read = (lambda path: globals()['api'](repository, path)) if api is None else api
    meta = _decode(read(f'actions/runs/{run}/attempts/{attempt}'))
    source = _run_identity(repository, meta, run, attempt)
    current = _decode(read(f'actions/runs/{run}'))
    if _run_identity(repository, current, run, attempt) != source:
        raise ValueError('Source run changed before checkpoint capture')
    inventory = _pages(read, f'actions/runs/{run}/artifacts', 'artifacts')
    if not inventory:
        if (attempt != 1 or meta['conclusion'] != 'cancelled'
                or _pages(read, f'actions/runs/{run}/attempts/{attempt}/jobs', 'jobs', require_total=True)):
            raise ValueError('Completed release has no retained checkpoint artifacts')
        # GitHub may cancel a queued first attempt before any job starts. This
        # narrow no-op cannot conceal a generation reservation or runner work.
        after = _decode(read(f'actions/runs/{run}'))
        if (_run_identity(repository, after, run, attempt) != source or after['conclusion'] != 'cancelled'
                or _pages(read, f'actions/runs/{run}/artifacts', 'artifacts')):
            raise ValueError('Cancelled empty release changed during checkpoint capture')
        _output_name('')
        return {'schema_version': SCHEMA_VERSION, 'artifact_name': '', 'source': source,
                'source_conclusion': meta['conclusion'], 'artifacts': []}
    if len(inventory) > MAX_ARTIFACTS:
        raise ValueError('Checkpoint source artifact count is empty or exceeds its limit')
    name = artifact_name(run, attempt, inventory)
    destination = Path(output)
    if destination.is_symlink() or (destination.exists() and any(destination.iterdir())):
        raise ValueError('Checkpoint capture destination must be empty')
    destination.mkdir(parents=True, exist_ok=True)
    (destination / 'artifacts').mkdir()
    items, identifiers, total = [], set(), 0
    for item in sorted(inventory, key=lambda value: _positive(value.get('id'))):
        identifier = _artifact(item, source)
        if identifier in identifiers:
            raise ValueError('Conflicting checkpoint artifact identities')
        identifiers.add(identifier)
        raw = read(f'actions/artifacts/{identifier}/zip')
        total += len(raw)
        if total > MAX_BUNDLE_BYTES or _sha(raw) != item['digest'].removeprefix('sha256:'):
            raise ValueError('Source artifact ZIP digest or aggregate size mismatch')
        with _members(raw):
            pass  # Inspect the central directory only; never extract payloads.
        path = f'artifacts/{identifier}.zip'
        with (destination / path).open('xb') as handle:
            handle.write(raw)
        items.append({'metadata': item, 'path': path, 'zip_sha256': _sha(raw), 'zip_bytes': len(raw)})
    after = _decode(read(f'actions/runs/{run}'))
    if (_run_identity(repository, after, run, attempt) != source
            or _pages(read, f'actions/runs/{run}/artifacts', 'artifacts') != inventory):
        raise ValueError('Source run or artifact inventory changed during checkpoint capture')
    manifest = {'schema_version': SCHEMA_VERSION, 'artifact_name': name, 'source': source,
                'source_conclusion': meta.get('conclusion'), 'artifacts': items}
    with (destination / 'manifest.json').open('xb') as handle:
        handle.write(_json(manifest))
    _output_name(name)
    return manifest


def _bundle(repository, run, outer, read):
    match = BACKUP_NAME.fullmatch(str(outer.get('name')))
    if not match or match.group(1) != str(run):
        raise ValueError('Checkpoint archive selector mismatch')
    attempt = int(match.group(2))
    backup_id = _positive((outer.get('workflow_run') or {}).get('id'))
    backup_meta = _decode(read(f'actions/runs/{backup_id}'))
    backup = _run_identity(repository, backup_meta, backup_id, backup=True)
    _artifact(outer, backup, outer=True)
    raw = read(f"actions/artifacts/{outer['id']}/zip")
    if _sha(raw) != outer['digest'].removeprefix('sha256:'):
        raise ValueError('Checkpoint archive GitHub digest mismatch')
    with _members(raw, outer=True) as archive:
        files = {item.filename for item in archive.infolist() if not item.is_dir()}
        try:
            info = archive.getinfo('manifest.json')
            if info.file_size > MAX_MANIFEST_BYTES:
                raise ValueError('Checkpoint manifest exceeds its byte limit')
            manifest_bytes = archive.read(info)
            manifest = _decode(manifest_bytes)
            if not isinstance(manifest, dict) or set(manifest) != MANIFEST_KEYS:
                raise ValueError('Unexpected checkpoint manifest keys')
        except (KeyError, ValueError, zipfile.BadZipFile) as error:
            raise ValueError('Checkpoint manifest is missing or invalid') from error
        source = manifest.get('source')
        exact_meta = _decode(read(f'actions/runs/{run}/attempts/{attempt}'))
        expected_source = _run_identity(repository, exact_meta, run, attempt)
        inventory = manifest.get('artifacts')
        if (type(manifest.get('schema_version')) is not int or manifest['schema_version'] != SCHEMA_VERSION
                or source != expected_source
                or manifest.get('source_conclusion') != exact_meta['conclusion']
                or manifest.get('artifact_name') != outer['name']
                or not isinstance(inventory, list) or not 0 < len(inventory) <= MAX_ARTIFACTS):
            raise ValueError('Checkpoint manifest source identity mismatch')
        records, contents, expected_files, total = [], {}, {'manifest.json'}, 0
        for item in inventory:
            if not isinstance(item, dict) or set(item) != ITEM_KEYS:
                raise ValueError('Unexpected checkpoint artifact item keys')
            metadata = item.get('metadata') or {}
            identifier = _artifact(metadata, source)
            path = f'artifacts/{identifier}.zip'
            if identifier in contents or item.get('path') != path:
                raise ValueError('Conflicting checkpoint payload identities')
            expected_files.add(path)
            try:
                info = archive.getinfo(path)
                if not 0 < info.file_size <= MAX_ZIP_BYTES:
                    raise ValueError('Preserved artifact exceeds its byte limit')
                inner = archive.read(info)
            except (KeyError, zipfile.BadZipFile) as error:
                raise ValueError('Preserved artifact ZIP missing or corrupt') from error
            total += len(inner)
            if (total > MAX_BUNDLE_BYTES or item.get('zip_bytes') != len(inner)
                    or item.get('zip_sha256') != _sha(inner)
                    or metadata['digest'] != 'sha256:' + _sha(inner)):
                raise ValueError('Preserved artifact ZIP digest mismatch')
            with _members(inner):
                pass
            provenance = {'backup_artifact_id': outer['id'], 'backup_run_id': str(backup_id),
                          'backup_name': outer['name'], 'source_run_id': str(run), 'source_attempt': attempt,
                          'backup_digest': outer['digest'], 'original_artifact_id': identifier,
                          'manifest_sha256': _sha(manifest_bytes), 'zip_sha256': _sha(inner)}
            records.append(dict(metadata, _checkpoint_archive=provenance))
            contents[identifier] = inner
        if files != expected_files or artifact_name(run, attempt, records) != outer['name']:
            raise ValueError('Checkpoint archive inventory or candidate selector mismatch')
    return records, contents


def preserved_artifacts(repository, run=None, *, candidate=None, task_prefix=None, inventory=None, api=None):
    """Return original records from authenticated independent backup artifacts.

    Repository inventory and the optional candidate suffix let report lookup
    reject unrelated archives before downloading their potentially large ZIPs.
    """
    repository = _repository(repository)
    if run is not None:
        run = str(_positive(run))
    if candidate is not None and not re.fullmatch(r'[a-f0-9]{64}', str(candidate)):
        raise ValueError('Invalid checkpoint candidate selector')
    if task_prefix is not None and (not isinstance(task_prefix, str) or not TASK_PREFIX.fullmatch(task_prefix)):
        raise ValueError('Invalid checkpoint task selector')
    task_digest = _sha(task_prefix.encode()) if task_prefix is not None else None
    read = (lambda path: globals()['api'](repository, path)) if api is None else api
    rows = _pages(read, 'actions/artifacts', 'artifacts') if inventory is None else inventory
    if not isinstance(rows, list) or len(rows) > MAX_PAGES * 100:
        raise ValueError('Checkpoint archive discovery exceeds its limit')
    selected = {}
    for outer in sorted(rows, key=lambda item: _positive(item.get('id'))):
        name = str(outer.get('name', ''))
        match = BACKUP_NAME.fullmatch(name)
        if not match or (run is not None and match.group(1) != run) or (candidate is not None and match.group(3) != candidate):
            continue
        # New archives advertise their complete task inventory in the name.
        # Mixed/uncertain inventories remain relevant to every task lookup.
        if task_digest is not None and match.group(4) != task_digest and not match.group(5):
            continue
        if outer.get('expired') is True:
            continue
        records, _ = _bundle(repository, match.group(1), outer, read)
        for record in records:
            identifier = record['id']
            previous = selected.get(identifier)
            if previous is not None:
                intrinsic = lambda value: {key: item for key, item in value.items() if key != '_checkpoint_archive'}
                if intrinsic(previous) != intrinsic(record):
                    raise ValueError('Independent archives disagree on an original artifact')
            selected[identifier] = record
    return list(selected.values())


def read_preserved_artifact(repository, run, artifact, *, api=None):
    """Reauthenticate the independent backup and return one exact original ZIP."""
    repository, run = _repository(repository), str(_positive(run))
    read = (lambda path: globals()['api'](repository, path)) if api is None else api
    provenance = artifact.get('_checkpoint_archive') or {}
    outer_id = _positive(provenance.get('backup_artifact_id'))
    outer = _decode(read(f'actions/artifacts/{outer_id}'))
    records, contents = _bundle(repository, run, outer, read)
    matches = [row for row in records if row == artifact]
    if len(matches) != 1:
        raise ValueError('Preserved artifact record or provenance changed')
    return contents[_positive(artifact.get('id'))]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    commands = parser.add_subparsers(dest='command', required=True)
    command = commands.add_parser('capture')
    command.add_argument('--repository', default=os.environ.get('GITHUB_REPOSITORY'))
    command.add_argument('--run', required=True)
    command.add_argument('--attempt', required=True)
    command.add_argument('--output', type=Path, required=True)
    args = parser.parse_args()
    result = capture(args.repository, args.run, args.attempt, args.output)
    print(json.dumps({'artifact_name': result['artifact_name'], 'artifacts': len(result['artifacts'])}))


if __name__ == '__main__':
    main()
